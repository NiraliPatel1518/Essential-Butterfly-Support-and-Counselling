package ca.sheridancollege.shtirthb.service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.Paths;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

import ca.sheridancollege.shtirthb.config.AppProperties;
import ca.sheridancollege.shtirthb.exception.AppExceptions;

/*
 * Keeps the files in a folder (app.memory-wall.storage-directory). With
 * Docker the folder is a volume, so the pictures survive a rebuild. Used
 * while app.memory-wall.storage is "local" (the default).
 */
@Component
@ConditionalOnProperty(
        prefix = "app.memory-wall",
        name = "storage",
        havingValue = "local",
        matchIfMissing = true)
public class LocalPhotoStorage implements PhotoStorage {

    private static final Logger logger =
            LoggerFactory.getLogger(LocalPhotoStorage.class);

    private final Path root;

    public LocalPhotoStorage(AppProperties properties) {

        this.root = Paths.get(
                        properties.getMemoryWall().getStorageDirectory())
                .toAbsolutePath()
                .normalize();
    }

    @Override
    public void store(String key, byte[] content, String contentType) {

        Path target = resolve(key);

        /*
         * Writing can fail with a checked IOException (disk full, no
         * permission). It is turned into the project's
         * ServiceUnavailableException, which the global handler answers with
         * a friendly message.
         */
        try {
            Files.createDirectories(target.getParent());
            Files.write(target, content);
        } catch (IOException exception) {
            throw new AppExceptions.ServiceUnavailableException(
                    "We could not save the photo right now. Please try again.",
                    exception);
        }
    }

    @Override
    public byte[] load(String key) {

        Path source = resolve(key);

        try {
            return Files.readAllBytes(source);
        } catch (NoSuchFileException exception) {
            throw new AppExceptions.ResourceNotFoundException("Photo");
        } catch (IOException exception) {
            throw new AppExceptions.ServiceUnavailableException(
                    "We could not open the photo right now. Please try again.",
                    exception);
        }
    }

    @Override
    public void delete(String key) {

        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException | RuntimeException exception) {
            logger.warn("Could not remove stored photo {}", key, exception);
        }
    }

    // Keys are generated by the application; this still refuses any key that
    // would point outside the storage folder.
    private Path resolve(String key) {

        Path path = root.resolve(key).normalize();

        if (!path.startsWith(root) || path.equals(root)) {
            throw new AppExceptions.ResourceNotFoundException("Photo");
        }

        return path;
    }
}
