-- =====================================================================
-- V11  UC-09 Manage website content and resources
--
--   1. website_content_pages   editable public pages (Services, About and
--                              Credentials, Privacy Policy). Every page keeps
--                              a PUBLISHED copy (what visitors see) and a
--                              DRAFT copy (what the administrator is editing).
--   2. library_resources       the public Resource Library: web links or
--                              uploaded documents / images.
--   3. library_resource_files  the bytes of an uploaded file, kept apart so
--                              lists never load them. Saved in the same
--                              transaction as the resource, so a failed
--                              save can never leave half a resource behind.
--   4. audit triggers          every content change is written to the
--                              existing append-only audit_log through
--                              fn_audit(), like the other tables. The acting
--                              administrator is passed by the application with
--                              set_config('app.actor', ...).
--
-- Visitors can only ever read rows with published content / status
-- 'PUBLISHED'. Drafts and soft-deleted resources are never exposed.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. editable pages
-- ---------------------------------------------------------------------
CREATE TABLE website_content_pages (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_key        varchar(40)  NOT NULL,
    published_title varchar(180),
    published_body  text,
    draft_title     varchar(180),
    draft_body      text,
    published_at    timestamp(6),
    created_at      timestamp(6) NOT NULL DEFAULT now(),
    updated_at      timestamp(6) NOT NULL DEFAULT now(),

    CONSTRAINT uq_website_content_pages_key UNIQUE (page_key),
    CONSTRAINT ck_website_content_pages_key
        CHECK (page_key IN ('services', 'about', 'privacy')),
    CONSTRAINT ck_website_content_pages_published_pair
        CHECK ((published_title IS NULL) = (published_body IS NULL)),
    CONSTRAINT ck_website_content_pages_published_not_blank
        CHECK (published_title IS NULL
               OR (btrim(published_title) <> '' AND btrim(published_body) <> '')),
    CONSTRAINT ck_website_content_pages_published_at
        CHECK (published_title IS NULL OR published_at IS NOT NULL)
);

-- The three pages always exist. Nothing is published yet, so the website
-- keeps showing its built-in text until an administrator publishes.
INSERT INTO website_content_pages (page_key)
VALUES ('services'), ('about'), ('privacy');

-- ---------------------------------------------------------------------
-- 2. resource library
-- ---------------------------------------------------------------------
CREATE TABLE library_resources (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             varchar(200)  NOT NULL,
    description       varchar(500)  NOT NULL,
    category          varchar(80)   NOT NULL,
    resource_type     varchar(10)   NOT NULL,
    link_url          varchar(2000),
    file_name         varchar(255),
    file_content_type varchar(100),
    file_size         bigint,
    alt_text          varchar(300),
    status            varchar(12)   NOT NULL,
    published_at      timestamp(6),
    created_at        timestamp(6)  NOT NULL DEFAULT now(),
    updated_at        timestamp(6)  NOT NULL DEFAULT now(),

    CONSTRAINT ck_library_resources_type
        CHECK (resource_type IN ('LINK', 'FILE')),
    CONSTRAINT ck_library_resources_status
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'DELETED')),
    CONSTRAINT ck_library_resources_text_not_blank
        CHECK (btrim(title) <> '' AND btrim(description) <> '' AND btrim(category) <> ''),
    -- a resource is either a link or a file, never both and never neither
    CONSTRAINT ck_library_resources_source
        CHECK (
            (resource_type = 'LINK'
                AND link_url IS NOT NULL
                AND file_name IS NULL
                AND file_content_type IS NULL
                AND file_size IS NULL)
         OR (resource_type = 'FILE'
                AND link_url IS NULL
                AND file_name IS NOT NULL
                AND file_content_type IS NOT NULL
                AND file_size IS NOT NULL
                AND file_size > 0)
        ),
    CONSTRAINT ck_library_resources_published_at
        CHECK (status <> 'PUBLISHED' OR published_at IS NOT NULL)
);

-- no two live resources may share a title (any capitalisation) or a link
CREATE UNIQUE INDEX ux_library_resources_title
    ON library_resources (lower(title))
    WHERE status <> 'DELETED';

CREATE UNIQUE INDEX ux_library_resources_link
    ON library_resources (link_url)
    WHERE link_url IS NOT NULL AND status <> 'DELETED';

CREATE INDEX ix_library_resources_public
    ON library_resources (title)
    WHERE status = 'PUBLISHED';

CREATE INDEX ix_library_resources_updated
    ON library_resources (updated_at DESC)
    WHERE status <> 'DELETED';

-- ---------------------------------------------------------------------
-- 3. uploaded file bytes
-- ---------------------------------------------------------------------
CREATE TABLE library_resource_files (
    resource_id bigint PRIMARY KEY,
    content     bytea NOT NULL,

    CONSTRAINT fk_library_resource_files_resource
        FOREIGN KEY (resource_id) REFERENCES library_resources (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_library_resource_files_not_empty
        CHECK (octet_length(content) > 0)
);

-- ---------------------------------------------------------------------
-- 4. audit trail (what changed and when; never the page text or the file)
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_audit_content_pages() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.draft_title IS DISTINCT FROM OLD.draft_title
       OR NEW.draft_body IS DISTINCT FROM OLD.draft_body THEN
        PERFORM fn_audit('CONTENT_DRAFT_SAVED', 'website_content_pages', NEW.id,
                         jsonb_build_object('page_key', NEW.page_key));
    END IF;

    IF NEW.published_at IS DISTINCT FROM OLD.published_at THEN
        PERFORM fn_audit('CONTENT_PUBLISHED', 'website_content_pages', NEW.id,
                         jsonb_build_object('page_key', NEW.page_key));
    END IF;

    RETURN NULL;
END
$$;

CREATE TRIGGER trg_audit_content_pages
    AFTER UPDATE ON website_content_pages
    FOR EACH ROW EXECUTE FUNCTION fn_audit_content_pages();

CREATE FUNCTION fn_audit_library_resources() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM fn_audit('RESOURCE_CREATED', 'library_resources', NEW.id,
                         jsonb_build_object('title', NEW.title,
                                            'type', NEW.resource_type,
                                            'status', NEW.status));
        RETURN NULL;
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status THEN
        IF NEW.status = 'DELETED' THEN
            PERFORM fn_audit('RESOURCE_REMOVED', 'library_resources', NEW.id,
                             jsonb_build_object('title', NEW.title));
        ELSIF NEW.status = 'PUBLISHED' THEN
            PERFORM fn_audit('RESOURCE_PUBLISHED', 'library_resources', NEW.id,
                             jsonb_build_object('title', NEW.title));
        ELSE
            PERFORM fn_audit('RESOURCE_UNPUBLISHED', 'library_resources', NEW.id,
                             jsonb_build_object('title', NEW.title));
        END IF;
    END IF;

    IF NEW.status <> 'DELETED'
       AND (NEW.title IS DISTINCT FROM OLD.title
            OR NEW.description IS DISTINCT FROM OLD.description
            OR NEW.category IS DISTINCT FROM OLD.category
            OR NEW.link_url IS DISTINCT FROM OLD.link_url
            OR NEW.file_name IS DISTINCT FROM OLD.file_name
            OR NEW.file_size IS DISTINCT FROM OLD.file_size
            OR NEW.alt_text IS DISTINCT FROM OLD.alt_text) THEN
        PERFORM fn_audit('RESOURCE_UPDATED', 'library_resources', NEW.id,
                         jsonb_build_object('title', NEW.title));
    END IF;

    RETURN NULL;
END
$$;

CREATE TRIGGER trg_audit_library_resources
    AFTER INSERT OR UPDATE ON library_resources
    FOR EACH ROW EXECUTE FUNCTION fn_audit_library_resources();
