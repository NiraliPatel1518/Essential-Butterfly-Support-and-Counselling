-- =====================================================================
-- V13  UC-11 Schedule and manage an appointment
--
--   1. appointment_availability  the administrator's WEEKLY pattern: one row
--                                is one slot that repeats every week
--                                (weekday + start time + length 30-120 min).
--                                Individual dates are never stored; the next
--                                seven days are worked out from these rows.
--   2. appointment_settings      one row: how many hours before its start an
--                                unbooked slot disappears from the website.
--   3. appointments              a client's booking request for ONE slot and
--                                what happened to it (Requested, Confirmed,
--                                Declined, Cancelled, Completed).
--   4. appointment_feedback      the administrator's feedback (shown to the
--                                client) and private notes (administrator
--                                only) for one appointment.
--   5. feature switch            the fourth feature-visibility toggle.
--   6. audit triggers            every change is written to the existing
--                                append-only audit_log through fn_audit(),
--                                exactly like the other tables.
--
-- Nothing about the client is copied: the name, e-mail address and phone
-- number are always read from client_users / account_emails. Times are the
-- clinic's local wall-clock time (the application converts "now" with the
-- configured time zone), the same timestamp(6) convention as every other
-- table.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1. weekly availability
-- ---------------------------------------------------------------------
CREATE TABLE appointment_availability (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    weekday      smallint     NOT NULL,   -- ISO: 1 = Monday ... 7 = Sunday
    start_time   time(0)      NOT NULL,
    slot_minutes smallint     NOT NULL,
    created_at   timestamp(6) NOT NULL DEFAULT now(),
    updated_at   timestamp(6) NOT NULL DEFAULT now(),

    CONSTRAINT ck_appointment_availability_weekday
        CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT ck_appointment_availability_length
        CHECK (slot_minutes BETWEEN 30 AND 120),
    -- a slot never runs past midnight
    CONSTRAINT ck_appointment_availability_same_day
        CHECK ((extract(epoch FROM start_time)::int / 60) + slot_minutes <= 1440),
    CONSTRAINT uq_appointment_availability_start
        UNIQUE (weekday, start_time),
    -- two weekly slots can never overlap
    CONSTRAINT ex_appointment_availability_overlap
        EXCLUDE USING gist (
            int4range(
                weekday * 1440 + (extract(epoch FROM start_time)::int / 60),
                weekday * 1440 + (extract(epoch FROM start_time)::int / 60) + slot_minutes
            ) WITH &&
        )
);

-- ---------------------------------------------------------------------
-- 2. settings (exactly one row)
-- ---------------------------------------------------------------------
CREATE TABLE appointment_settings (
    id                     smallint     PRIMARY KEY,
    hide_hours_before_start smallint    NOT NULL DEFAULT 3,
    updated_at             timestamp(6) NOT NULL DEFAULT now(),

    CONSTRAINT ck_appointment_settings_single_row CHECK (id = 1),
    CONSTRAINT ck_appointment_settings_hours
        CHECK (hide_hours_before_start BETWEEN 0 AND 168)
);

INSERT INTO appointment_settings (id, hide_hours_before_start) VALUES (1, 3);

-- ---------------------------------------------------------------------
-- 3. appointments
-- ---------------------------------------------------------------------
CREATE TABLE appointments (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id         bigint,
    starts_at         timestamp(6) NOT NULL,
    ends_at           timestamp(6) NOT NULL,
    status            varchar(10)  NOT NULL DEFAULT 'REQUESTED',
    status_reason     varchar(500),
    meeting_link      varchar(2000),
    meeting_link_sent_at timestamp(6),
    google_event_id   varchar(255),
    requested_at      timestamp(6) NOT NULL DEFAULT now(),
    updated_at        timestamp(6) NOT NULL DEFAULT now(),

    -- history survives the client's account (same rule as intake / testimonials)
    CONSTRAINT fk_appointments_client
        FOREIGN KEY (client_id) REFERENCES client_users (id)
        ON DELETE SET NULL,

    CONSTRAINT ck_appointments_status
        CHECK (status IN ('REQUESTED', 'CONFIRMED', 'DECLINED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT ck_appointments_length
        CHECK (ends_at - starts_at BETWEEN interval '30 minutes' AND interval '2 hours'),
    -- a reason is mandatory for a decline, optional for a cancellation and
    -- never present otherwise
    CONSTRAINT ck_appointments_reason
        CHECK (
            (status = 'DECLINED'  AND status_reason IS NOT NULL AND btrim(status_reason) <> '')
         OR (status = 'CANCELLED' AND (status_reason IS NULL OR btrim(status_reason) <> ''))
         OR (status IN ('REQUESTED', 'CONFIRMED', 'COMPLETED') AND status_reason IS NULL)
        ),
    -- only an accepted appointment has a meeting link or a calendar event
    CONSTRAINT ck_appointments_link_status
        CHECK (meeting_link IS NULL OR status IN ('CONFIRMED', 'COMPLETED')),
    CONSTRAINT ck_appointments_link_not_blank
        CHECK (meeting_link IS NULL OR btrim(meeting_link) <> ''),
    CONSTRAINT ck_appointments_link_sent
        CHECK (meeting_link_sent_at IS NULL OR meeting_link IS NOT NULL),
    CONSTRAINT ck_appointments_event_status
        CHECK (google_event_id IS NULL OR status IN ('CONFIRMED', 'COMPLETED')),

    -- Double-booking is impossible: while a request is waiting or accepted
    -- no other waiting / accepted appointment may touch the same time.
    CONSTRAINT ex_appointments_no_double_booking
        EXCLUDE USING gist (tsrange(starts_at, ends_at) WITH &&)
        WHERE (status IN ('REQUESTED', 'CONFIRMED'))
);

CREATE INDEX ix_appointments_client
    ON appointments (client_id, starts_at DESC);

CREATE INDEX ix_appointments_status_start
    ON appointments (status, starts_at);

CREATE INDEX ix_appointments_start
    ON appointments (starts_at DESC);

-- ---------------------------------------------------------------------
-- 4. feedback and private notes (kept for ever)
-- ---------------------------------------------------------------------
CREATE TABLE appointment_feedback (
    appointment_id bigint       PRIMARY KEY,
    feedback       text,
    private_notes  text,
    created_at     timestamp(6) NOT NULL DEFAULT now(),
    updated_at     timestamp(6) NOT NULL DEFAULT now(),

    CONSTRAINT fk_appointment_feedback_appointment
        FOREIGN KEY (appointment_id) REFERENCES appointments (id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_appointment_feedback_something
        CHECK (feedback IS NOT NULL OR private_notes IS NOT NULL),
    CONSTRAINT ck_appointment_feedback_not_blank
        CHECK ((feedback IS NULL OR btrim(feedback) <> '')
           AND (private_notes IS NULL OR btrim(private_notes) <> '')),
    CONSTRAINT ck_appointment_feedback_length
        CHECK (char_length(feedback) <= 4000 AND char_length(private_notes) <= 4000)
);

-- Appointments and their feedback are a permanent record.
CREATE FUNCTION fn_forbid_delete() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% rows are kept permanently and cannot be deleted', TG_TABLE_NAME;
END
$$;

CREATE TRIGGER trg_appointments_keep
    BEFORE DELETE ON appointments
    FOR EACH ROW EXECUTE FUNCTION fn_forbid_delete();

CREATE TRIGGER trg_appointment_feedback_keep
    BEFORE DELETE ON appointment_feedback
    FOR EACH ROW EXECUTE FUNCTION fn_forbid_delete();

-- ---------------------------------------------------------------------
-- 5. the fourth feature toggle
-- ---------------------------------------------------------------------
INSERT INTO public_feature_visibility (feature_key, label, enabled, display_order)
VALUES ('APPOINTMENTS', 'Appointments', true, 4)
ON CONFLICT (feature_key) DO NOTHING;

-- ---------------------------------------------------------------------
-- 6. audit trail (what happened and when; never the feedback, the notes or
--    the meeting link)
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_audit_appointment_availability() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM fn_audit('AVAILABILITY_ADDED', 'appointment_availability', NEW.id,
                         jsonb_build_object('weekday', NEW.weekday,
                                            'start_time', NEW.start_time,
                                            'slot_minutes', NEW.slot_minutes));
    ELSIF TG_OP = 'UPDATE' THEN
        PERFORM fn_audit('AVAILABILITY_CHANGED', 'appointment_availability', NEW.id,
                         jsonb_build_object('weekday', NEW.weekday,
                                            'start_time', NEW.start_time,
                                            'slot_minutes', NEW.slot_minutes));
    ELSE
        PERFORM fn_audit('AVAILABILITY_REMOVED', 'appointment_availability', OLD.id,
                         jsonb_build_object('weekday', OLD.weekday,
                                            'start_time', OLD.start_time,
                                            'slot_minutes', OLD.slot_minutes));
    END IF;
    RETURN NULL;
END
$$;

CREATE TRIGGER trg_audit_appointment_availability
    AFTER INSERT OR UPDATE OR DELETE ON appointment_availability
    FOR EACH ROW EXECUTE FUNCTION fn_audit_appointment_availability();

CREATE FUNCTION fn_audit_appointment_settings() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.hide_hours_before_start IS DISTINCT FROM OLD.hide_hours_before_start THEN
        PERFORM fn_audit('APPOINTMENT_SETTINGS_CHANGED', 'appointment_settings', NEW.id,
                         jsonb_build_object('hide_hours_before_start',
                                            NEW.hide_hours_before_start));
    END IF;
    RETURN NULL;
END
$$;

CREATE TRIGGER trg_audit_appointment_settings
    AFTER UPDATE ON appointment_settings
    FOR EACH ROW EXECUTE FUNCTION fn_audit_appointment_settings();

CREATE FUNCTION fn_audit_appointments() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM fn_audit('APPOINTMENT_REQUESTED', 'appointments', NEW.id,
                         jsonb_build_object('client_id', NEW.client_id,
                                            'starts_at', NEW.starts_at));
        RETURN NULL;
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status THEN
        PERFORM fn_audit('APPOINTMENT_' || NEW.status, 'appointments', NEW.id,
                         jsonb_build_object('from', OLD.status,
                                            'to', NEW.status,
                                            'starts_at', NEW.starts_at));
    END IF;

    IF NEW.meeting_link IS DISTINCT FROM OLD.meeting_link THEN
        PERFORM fn_audit('APPOINTMENT_LINK_SAVED', 'appointments', NEW.id, '{}');
    END IF;

    IF NEW.meeting_link_sent_at IS DISTINCT FROM OLD.meeting_link_sent_at
       AND NEW.meeting_link_sent_at IS NOT NULL THEN
        PERFORM fn_audit('APPOINTMENT_INVITATION_SENT', 'appointments', NEW.id, '{}');
    END IF;

    IF NEW.google_event_id IS DISTINCT FROM OLD.google_event_id THEN
        PERFORM fn_audit(
            CASE WHEN NEW.google_event_id IS NULL
                 THEN 'APPOINTMENT_CALENDAR_REMOVED'
                 ELSE 'APPOINTMENT_CALENDAR_ADDED' END,
            'appointments', NEW.id, '{}');
    END IF;

    RETURN NULL;
END
$$;

CREATE TRIGGER trg_audit_appointments
    AFTER INSERT OR UPDATE ON appointments
    FOR EACH ROW EXECUTE FUNCTION fn_audit_appointments();

CREATE FUNCTION fn_audit_appointment_feedback() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    PERFORM fn_audit('APPOINTMENT_FEEDBACK_SAVED', 'appointment_feedback', NEW.appointment_id,
                     jsonb_build_object('has_feedback', NEW.feedback IS NOT NULL,
                                        'has_private_notes', NEW.private_notes IS NOT NULL));
    RETURN NULL;
END
$$;

CREATE TRIGGER trg_audit_appointment_feedback
    AFTER INSERT OR UPDATE ON appointment_feedback
    FOR EACH ROW EXECUTE FUNCTION fn_audit_appointment_feedback();
