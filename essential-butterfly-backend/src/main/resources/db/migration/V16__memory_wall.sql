-- =====================================================================
-- V16  UC-12  Memory Wall (the media gallery)
--
-- One new table, memory_wall_photos: one row per photo that can appear on
-- the public Memory Wall. A photo comes from exactly one of two places:
--
--   ADMIN_UPLOAD  uploaded by the administrator on Manage Memory Wall.
--                 The picture itself is kept in the photo store (a folder
--                 today, an AWS S3 bucket later); this row keeps only its
--                 storage_key, so moving to S3 never changes the database.
--   TESTIMONIAL   a photo a client attached to a testimonial. Nothing is
--                 copied: the row points at the existing testimonial_photos
--                 row (testimonial_id + photo_order) and the picture stays
--                 where it already is. A trigger adds the row, so every
--                 customer photo reaches Manage Memory Wall automatically.
--
-- Status (PENDING_REVIEW -> PUBLISHED <-> UNPUBLISHED) is the only
-- publication state. A new photo is always PENDING_REVIEW and is never
-- public until the administrator selects it. Who uploaded it and when is
-- kept (uploaded_at, uploaded_by_admin_id or the testimonial's client).
--
-- Deleting a photo removes its row for good (and, for an admin upload, its
-- file). A photo that belongs to a testimonial is only removed from the
-- Memory Wall; it stays with the client's testimonial.
--
-- Every add / publish / unpublish / description change / delete is written
-- to the existing append-only audit_log through fn_audit(), like every
-- other table.
-- =====================================================================

CREATE TABLE memory_wall_photos (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source               varchar(20)  NOT NULL,
    storage_key          varchar(120),
    original_filename    varchar(255),
    testimonial_id       bigint,
    photo_order          integer,
    content_type         varchar(30)  NOT NULL,
    size_bytes           integer      NOT NULL,
    description          varchar(200),
    status               varchar(20)  NOT NULL DEFAULT 'PENDING_REVIEW',
    uploaded_by_admin_id bigint,
    uploaded_at          timestamp(6) NOT NULL DEFAULT now(),
    published_at         timestamp(6),
    updated_at           timestamp(6) NOT NULL DEFAULT now(),

    CONSTRAINT ck_memory_wall_photos_source
        CHECK (source IN ('ADMIN_UPLOAD', 'TESTIMONIAL')),
    CONSTRAINT ck_memory_wall_photos_status
        CHECK (status IN ('PENDING_REVIEW', 'PUBLISHED', 'UNPUBLISHED')),
    CONSTRAINT ck_memory_wall_photos_type
        CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT ck_memory_wall_photos_size
        CHECK (size_bytes > 0),
    CONSTRAINT ck_memory_wall_photos_description
        CHECK (description IS NULL OR btrim(description) <> ''),
    CONSTRAINT ck_memory_wall_photos_published_at
        CHECK ((status = 'PUBLISHED') = (published_at IS NOT NULL)),
    CONSTRAINT ck_memory_wall_photos_origin
        CHECK (
            (source = 'ADMIN_UPLOAD'
                AND storage_key IS NOT NULL AND btrim(storage_key) <> ''
                AND original_filename IS NOT NULL AND btrim(original_filename) <> ''
                AND testimonial_id IS NULL AND photo_order IS NULL)
            OR
            (source = 'TESTIMONIAL'
                AND testimonial_id IS NOT NULL AND photo_order IS NOT NULL
                AND storage_key IS NULL AND original_filename IS NULL
                AND uploaded_by_admin_id IS NULL)
        ),

    CONSTRAINT uq_memory_wall_photos_storage_key UNIQUE (storage_key),
    CONSTRAINT uq_memory_wall_photos_testimonial_photo
        UNIQUE (testimonial_id, photo_order),

    CONSTRAINT fk_memory_wall_photos_admin
        FOREIGN KEY (uploaded_by_admin_id) REFERENCES admin_users (id)
        ON DELETE SET NULL,
    CONSTRAINT fk_memory_wall_photos_testimonial_photo
        FOREIGN KEY (testimonial_id, photo_order)
        REFERENCES testimonial_photos (testimonial_id, photo_order)
        ON DELETE CASCADE
);

-- public page: published photos, newest first; admin page: everything newest first
CREATE INDEX ix_memory_wall_photos_status_uploaded
    ON memory_wall_photos (status, uploaded_at DESC);
CREATE INDEX ix_memory_wall_photos_uploaded
    ON memory_wall_photos (uploaded_at DESC);

-- ---------------------------------------------------------------------
-- Customer photos reach the wall by themselves
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_memory_wall_from_testimonial_photo() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    v_kind    text;
    v_created timestamp(6);
BEGIN
    v_kind := substring(NEW.photo_data FROM '^data:image/(jpeg|jpg|png|webp);base64,');

    IF v_kind IS NULL THEN
        RETURN NULL;     -- not a picture the wall can show
    END IF;

    SELECT created_at INTO v_created
      FROM customer_testimonials
     WHERE id = NEW.testimonial_id;

    INSERT INTO memory_wall_photos
        (source, testimonial_id, photo_order, content_type, size_bytes, uploaded_at)
    VALUES
        ('TESTIMONIAL', NEW.testimonial_id, NEW.photo_order,
         CASE v_kind WHEN 'png' THEN 'image/png'
                     WHEN 'webp' THEN 'image/webp'
                     ELSE 'image/jpeg' END,
         GREATEST(1, ((length(NEW.photo_data)
                       - length(substring(NEW.photo_data FROM '^data:[^,]*,'))) * 3) / 4),
         COALESCE(v_created, now()));

    RETURN NULL;
END
$$;

-- photos that clients attached before this release
INSERT INTO memory_wall_photos
    (source, testimonial_id, photo_order, content_type, size_bytes, uploaded_at)
SELECT 'TESTIMONIAL', p.testimonial_id, p.photo_order,
       CASE substring(p.photo_data FROM '^data:image/(jpeg|jpg|png|webp);base64,')
            WHEN 'png' THEN 'image/png'
            WHEN 'webp' THEN 'image/webp'
            ELSE 'image/jpeg' END,
       GREATEST(1, ((length(p.photo_data)
                     - length(substring(p.photo_data FROM '^data:[^,]*,'))) * 3) / 4),
       t.created_at
  FROM testimonial_photos p
  JOIN customer_testimonials t ON t.id = p.testimonial_id
 WHERE p.photo_data ~ '^data:image/(jpeg|jpg|png|webp);base64,';

CREATE TRIGGER trg_memory_wall_from_testimonial_photo
    AFTER INSERT ON testimonial_photos
    FOR EACH ROW EXECUTE FUNCTION fn_memory_wall_from_testimonial_photo();

-- ---------------------------------------------------------------------
-- Audit trail (what happened and when; never the picture itself).
-- Created after the back-fill above so old photos do not flood the log.
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_audit_memory_wall_photos() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        PERFORM fn_audit('MEMORY_WALL_PHOTO_ADDED', 'memory_wall_photos', NEW.id,
                         jsonb_build_object('title',
                                            COALESCE(NEW.original_filename, 'Testimonial photo'),
                                            'source', NEW.source));
        RETURN NULL;
    END IF;

    IF TG_OP = 'DELETE' THEN
        PERFORM fn_audit('MEMORY_WALL_PHOTO_DELETED', 'memory_wall_photos', OLD.id,
                         jsonb_build_object('title',
                                            COALESCE(OLD.original_filename, 'Testimonial photo'),
                                            'status', OLD.status));
        RETURN NULL;
    END IF;

    IF NEW.status IS DISTINCT FROM OLD.status THEN
        IF NEW.status = 'PUBLISHED' THEN
            PERFORM fn_audit('MEMORY_WALL_PHOTO_PUBLISHED', 'memory_wall_photos', NEW.id,
                             jsonb_build_object('title',
                                                COALESCE(NEW.original_filename, 'Testimonial photo')));
        ELSE
            PERFORM fn_audit('MEMORY_WALL_PHOTO_UNPUBLISHED', 'memory_wall_photos', NEW.id,
                             jsonb_build_object('title',
                                                COALESCE(NEW.original_filename, 'Testimonial photo')));
        END IF;
    END IF;

    IF NEW.description IS DISTINCT FROM OLD.description THEN
        PERFORM fn_audit('MEMORY_WALL_PHOTO_UPDATED', 'memory_wall_photos', NEW.id,
                         jsonb_build_object('title',
                                            COALESCE(NEW.original_filename, 'Testimonial photo')));
    END IF;

    RETURN NULL;
END
$$;

CREATE TRIGGER trg_audit_memory_wall_photos
    AFTER INSERT OR UPDATE OR DELETE ON memory_wall_photos
    FOR EACH ROW EXECUTE FUNCTION fn_audit_memory_wall_photos();
