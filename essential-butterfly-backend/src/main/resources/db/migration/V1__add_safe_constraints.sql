-- =====================================================================
-- V1  Safe constraints
--
-- Part A  Baseline guard
--         Existing databases already contain the legacy schema, so this
--         part does nothing for them. A brand-new, empty database (new
--         docker volume, CI, a teammate's machine) gets the legacy tables
--         created here so that V2..V9 can restructure them exactly the
--         same way they restructure production data.
--
-- Part B  Data clean-up that is always safe (trim / lower-case) followed
--         by constraints that cannot reject any valid application data.
--         Only constraints on columns that SURVIVE the restructuring are
--         added here; constraints for restructured tables live in the
--         migration that restructures them.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Part A: baseline guard (legacy schema, created only when missing)
-- ---------------------------------------------------------------------
DO $baseline$
BEGIN
    IF to_regclass('public.admin_users') IS NOT NULL THEN
        RETURN;
    END IF;

    CREATE TABLE admin_users (
        id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at                  timestamp(6) NOT NULL,
        email                       varchar(255) NOT NULL UNIQUE,
        failed_login_attempts       integer NOT NULL DEFAULT 0,
        full_name                   varchar(255) NOT NULL,
        locked_until                timestamp(6),
        password                    varchar(255) NOT NULL,
        email_change_otp_attempts   integer NOT NULL DEFAULT 0,
        email_change_otp_expiry     timestamp(6),
        email_change_otp_hash       varchar(100),
        email_change_otp_last_sent_at timestamp(6),
        email_change_otp_resend_count integer NOT NULL DEFAULT 0,
        login_challenge_token_hash  varchar(100),
        login_otp_attempts          integer NOT NULL DEFAULT 0,
        login_otp_expiry            timestamp(6),
        login_otp_hash              varchar(100),
        login_otp_last_sent_at      timestamp(6),
        login_otp_resend_count      integer NOT NULL DEFAULT 0,
        pending_email               varchar(254)
    );

    CREATE TABLE client_users (
        id                              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at                      timestamp(6) NOT NULL,
        email                           varchar(255) NOT NULL UNIQUE,
        full_name                       varchar(255) NOT NULL,
        password                        varchar(255) NOT NULL,
        email_verification_attempts     integer NOT NULL DEFAULT 0,
        email_verification_code_expiry  timestamp(6),
        email_verification_code_hash    varchar(100),
        email_verification_last_sent_at timestamp(6),
        email_verified                  boolean NOT NULL DEFAULT true,
        email_verification_resend_count integer NOT NULL DEFAULT 0,
        pending_phone_number            varchar(20),
        phone_number                    varchar(20),
        phone_verification_attempts     integer NOT NULL DEFAULT 0,
        phone_verification_code_expiry  timestamp(6),
        phone_verification_code_hash    varchar(100),
        phone_verification_last_sent_at timestamp(6),
        phone_verification_resend_count integer NOT NULL DEFAULT 0,
        phone_verified                  boolean NOT NULL DEFAULT false
    );

    CREATE TABLE contact_messages (
        id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at     timestamp(6) NOT NULL,
        email          varchar(255) NOT NULL,
        full_name      varchar(255) NOT NULL,
        message        text NOT NULL,
        status         varchar(255) NOT NULL,
        subject        varchar(255) NOT NULL,
        client_user_id bigint REFERENCES client_users (id)
    );

    CREATE TABLE customer_testimonials (
        id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        content             varchar(5000) NOT NULL,
        created_at          timestamp(6) NOT NULL,
        display_name        varchar(80) NOT NULL,
        display_on_public   boolean NOT NULL,
        featured_on_home    boolean NOT NULL,
        publication_consent boolean NOT NULL,
        reviewed_at         timestamp(6),
        status              varchar(20) NOT NULL,
        client_user_id      bigint NOT NULL REFERENCES client_users (id)
    );

    CREATE TABLE testimonial_photos (
        testimonial_id bigint NOT NULL REFERENCES customer_testimonials (id),
        photo_data     text,
        photo_order    integer NOT NULL CHECK (photo_order >= 0),
        PRIMARY KEY (testimonial_id, photo_order)
    );

    CREATE TABLE intake_submissions (
        id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        additional_notes         text,
        client_full_name         varchar(255) NOT NULL,
        contact_info             varchar(255) NOT NULL,
        created_at               timestamp(6) NOT NULL,
        overview                 text NOT NULL,
        parent_guardian_name     varchar(255),
        preferred_contact_method varchar(255) NOT NULL,
        rejection_reason         text,
        respite_goals            text,
        status                   varchar(255) NOT NULL,
        subject_focus            text,
        support_needs            text NOT NULL,
        client_user_id           bigint NOT NULL REFERENCES client_users (id)
    );

    CREATE TABLE newsletter_campaigns (
        id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        content         text NOT NULL,
        created_at      timestamp(6) NOT NULL,
        failed_count    integer NOT NULL,
        recipient_count integer NOT NULL,
        sent_at         timestamp(6),
        status          varchar(30) NOT NULL,
        subject         varchar(200) NOT NULL,
        success_count   integer NOT NULL
    );

    CREATE TABLE newsletter_subscribers (
        id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        active            boolean NOT NULL,
        consent_at        timestamp(6),
        consent_given     boolean NOT NULL,
        created_at        timestamp(6) NOT NULL,
        email             varchar(254) NOT NULL UNIQUE,
        unsubscribe_token varchar(36) NOT NULL UNIQUE,
        unsubscribed_at   timestamp(6)
    );

    CREATE TABLE newsletter_deliveries (
        id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        error_message varchar(1000),
        sent_at       timestamp(6),
        status        varchar(20) NOT NULL,
        campaign_id   bigint NOT NULL REFERENCES newsletter_campaigns (id),
        subscriber_id bigint NOT NULL REFERENCES newsletter_subscribers (id),
        UNIQUE (campaign_id, subscriber_id)
    );

    CREATE TABLE password_reset_tokens (
        id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        expires_at timestamp(6) NOT NULL,
        token      varchar(100) NOT NULL UNIQUE,
        used       boolean NOT NULL,
        user_id    bigint NOT NULL,
        user_type  varchar(255) NOT NULL
    );

    CREATE TABLE public_feature_visibility (
        id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        display_order integer NOT NULL,
        enabled       boolean NOT NULL,
        feature_key   varchar(40) NOT NULL UNIQUE,
        label         varchar(100) NOT NULL
    );

    CREATE TABLE website_updates (
        id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        content    text NOT NULL,
        created_at timestamp(6) NOT NULL,
        published  boolean NOT NULL,
        title      varchar(180) NOT NULL,
        updated_at timestamp(6) NOT NULL
    );

    CREATE TABLE website_update_photos (
        update_id   bigint NOT NULL REFERENCES website_updates (id),
        photo_data  text NOT NULL,
        photo_order integer NOT NULL CHECK (photo_order >= 0),
        PRIMARY KEY (update_id, photo_order)
    );

    CREATE TABLE website_update_social_links (
        update_id   bigint NOT NULL REFERENCES website_updates (id),
        social_link varchar(1000) NOT NULL,
        link_order  integer NOT NULL CHECK (link_order >= 0),
        PRIMARY KEY (update_id, link_order)
    );
END
$baseline$;

-- ---------------------------------------------------------------------
-- Part B1: normalise data so the constraints below can never fail
-- ---------------------------------------------------------------------
UPDATE contact_messages
   SET email = lower(btrim(email))
 WHERE email <> lower(btrim(email));

UPDATE newsletter_subscribers
   SET email = lower(btrim(email))
 WHERE email <> lower(btrim(email));

UPDATE admin_users
   SET full_name = btrim(full_name)
 WHERE full_name <> btrim(full_name);

UPDATE client_users
   SET full_name = btrim(full_name)
 WHERE full_name <> btrim(full_name);

DELETE FROM testimonial_photos WHERE photo_data IS NULL OR btrim(photo_data) = '';
DELETE FROM website_update_photos WHERE btrim(photo_data) = '';
DELETE FROM website_update_social_links WHERE btrim(social_link) = '';

UPDATE public_feature_visibility
   SET feature_key = upper(btrim(feature_key))
 WHERE feature_key <> upper(btrim(feature_key));

-- ---------------------------------------------------------------------
-- Part B2: constraints on columns that survive the restructuring
-- ---------------------------------------------------------------------

-- Admin accounts
ALTER TABLE admin_users
    ADD CONSTRAINT ck_admin_users_full_name_not_blank
        CHECK (btrim(full_name) <> ''),
    ADD CONSTRAINT ck_admin_users_failed_attempts_non_negative
        CHECK (failed_login_attempts >= 0),
    ADD CONSTRAINT ck_admin_users_login_otp_counters_non_negative
        CHECK (login_otp_attempts >= 0 AND login_otp_resend_count >= 0);

-- Client accounts
ALTER TABLE client_users
    ADD CONSTRAINT ck_client_users_full_name_not_blank
        CHECK (btrim(full_name) <> '');

-- Feature visibility
ALTER TABLE public_feature_visibility
    ADD CONSTRAINT ck_feature_visibility_key_format
        CHECK (feature_key ~ '^[A-Z][A-Z0-9_]*$'),
    ADD CONSTRAINT ck_feature_visibility_label_not_blank
        CHECK (btrim(label) <> ''),
    ADD CONSTRAINT ck_feature_visibility_order_non_negative
        CHECK (display_order >= 0);

-- Website updates and their child rows
ALTER TABLE website_updates
    ADD CONSTRAINT ck_website_updates_title_not_blank
        CHECK (btrim(title) <> ''),
    ADD CONSTRAINT ck_website_updates_content_not_blank
        CHECK (btrim(content) <> '');

ALTER TABLE website_update_photos
    ADD CONSTRAINT ck_website_update_photos_data_not_blank
        CHECK (btrim(photo_data) <> '');

ALTER TABLE website_update_social_links
    ADD CONSTRAINT ck_website_update_social_links_not_blank
        CHECK (btrim(social_link) <> '');

-- Testimonial photos must actually contain data
ALTER TABLE testimonial_photos
    ALTER COLUMN photo_data SET NOT NULL;

ALTER TABLE testimonial_photos
    ADD CONSTRAINT ck_testimonial_photos_data_not_blank
        CHECK (btrim(photo_data) <> '');

-- Newsletter subscribers: addresses are always stored lower-case, which
-- turns the existing UNIQUE(email) into a case-insensitive guarantee.
ALTER TABLE newsletter_subscribers
    ADD CONSTRAINT ck_newsletter_subscribers_email_format
        CHECK (email = lower(email) AND position('@' IN email) > 1);
