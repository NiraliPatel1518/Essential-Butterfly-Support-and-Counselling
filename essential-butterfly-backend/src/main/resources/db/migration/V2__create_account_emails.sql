-- =====================================================================
-- V2  account_emails
--
-- One table owns every e-mail address that belongs to an account, for
-- both account types:
--
--   * exactly one owner: an administrator OR a client (never both/none)
--   * a single global uniqueness rule across admins, clients AND
--     pending (not yet verified) e-mail changes
--   * is_primary = the address used to sign in
--   * is_primary = false rows are PENDING changes; there is at most one
--     per account and it can never be verified-and-primary at once
--   * the one-time-code verification state lives with the address it
--     verifies (hash only, never the code itself)
--
-- Data is moved in V3. This migration only creates the structure.
-- =====================================================================

CREATE TABLE account_emails (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    admin_user_id        bigint REFERENCES admin_users (id)  ON DELETE CASCADE,
    client_user_id       bigint REFERENCES client_users (id) ON DELETE CASCADE,

    email                varchar(254) NOT NULL,
    is_primary           boolean      NOT NULL DEFAULT false,

    created_at           timestamp(6) NOT NULL DEFAULT now(),
    verified_at          timestamp(6),

    -- one-time-code verification state (hash only)
    code_hash            varchar(100),
    code_expires_at      timestamp(6),
    code_last_sent_at    timestamp(6),
    code_attempts        integer NOT NULL DEFAULT 0,
    code_resend_count    integer NOT NULL DEFAULT 0,

    -- exactly one owner
    CONSTRAINT ck_account_emails_single_owner
        CHECK ((admin_user_id IS NOT NULL)::int + (client_user_id IS NOT NULL)::int = 1),

    -- canonical form: lower-case, no padding, looks like an address
    CONSTRAINT ck_account_emails_canonical
        CHECK (email = lower(btrim(email))
               AND position('@' IN email) > 1
               AND email !~ '\s'),

    -- a pending (non-primary) address is by definition not verified yet
    CONSTRAINT ck_account_emails_pending_unverified
        CHECK (is_primary OR verified_at IS NULL),

    -- administrators can only sign in with a verified address
    -- (clients may briefly hold an unverified primary right after signup)
    CONSTRAINT ck_account_emails_admin_primary_verified
        CHECK (admin_user_id IS NULL OR NOT is_primary OR verified_at IS NOT NULL),

    -- a verified address no longer carries a pending code
    CONSTRAINT ck_account_emails_verified_has_no_code
        CHECK (verified_at IS NULL OR code_hash IS NULL),

    CONSTRAINT ck_account_emails_counters_non_negative
        CHECK (code_attempts >= 0 AND code_resend_count >= 0),

    -- global uniqueness (admins + clients + pending changes).
    -- email is canonical lower-case, so plain UNIQUE is case-insensitive.
    CONSTRAINT uq_account_emails_email UNIQUE (email)
);

-- exactly one sign-in address per account
CREATE UNIQUE INDEX uq_account_emails_primary_per_admin
    ON account_emails (admin_user_id)
    WHERE is_primary AND admin_user_id IS NOT NULL;

CREATE UNIQUE INDEX uq_account_emails_primary_per_client
    ON account_emails (client_user_id)
    WHERE is_primary AND client_user_id IS NOT NULL;

-- at most one pending change per account
CREATE UNIQUE INDEX uq_account_emails_pending_per_admin
    ON account_emails (admin_user_id)
    WHERE NOT is_primary AND admin_user_id IS NOT NULL;

CREATE UNIQUE INDEX uq_account_emails_pending_per_client
    ON account_emails (client_user_id)
    WHERE NOT is_primary AND client_user_id IS NOT NULL;
