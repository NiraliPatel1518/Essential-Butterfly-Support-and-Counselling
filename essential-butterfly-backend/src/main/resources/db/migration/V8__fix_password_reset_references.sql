-- =====================================================================
-- V8  Password reset tokens
--
-- Problems fixed
--   * user_type + user_id was a polymorphic reference: no foreign key,
--     so a token could point at an account that does not exist (or was
--     deleted) and the database could not tell.
--   * the secret token itself was stored in clear text, so anyone who
--     could read the table could reset any password.
--   * "used" was a flag with no time, and any number of tokens could be
--     live for one account at the same time.
--
-- Result
--   * two real foreign keys (admin_user_id / client_user_id), exactly one
--     of them set, ON DELETE CASCADE (a deleted account has no tokens)
--   * only a SHA-256 hash of the token is stored; the application hashes
--     the token from the link and looks the hash up
--   * used_at records when the token was consumed
--   * at most ONE unused token per account at any time
-- =====================================================================

-- 1. capture what exists today (hashing the clear-text tokens) --------
CREATE TEMP TABLE tmp_password_reset_tokens ON COMMIT DROP AS
SELECT encode(sha256(convert_to(t.token, 'UTF8')), 'hex')            AS token_hash,
       CASE WHEN upper(t.user_type) = 'ADMIN'  THEN t.user_id END    AS admin_user_id,
       CASE WHEN upper(t.user_type) = 'CLIENT' THEN t.user_id END    AS client_user_id,
       t.expires_at,
       t.expires_at - interval '30 minutes'                          AS created_at,
       CASE WHEN t.used THEN t.expires_at - interval '30 minutes' END AS used_at
  FROM password_reset_tokens t;

DROP TABLE password_reset_tokens;

-- 2. new structure ------------------------------------------------------
CREATE TABLE password_reset_tokens (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    admin_user_id  bigint REFERENCES admin_users (id)  ON DELETE CASCADE,
    client_user_id bigint REFERENCES client_users (id) ON DELETE CASCADE,
    token_hash     varchar(64)  NOT NULL,
    created_at     timestamp(6) NOT NULL DEFAULT now(),
    expires_at     timestamp(6) NOT NULL,
    used_at        timestamp(6),

    CONSTRAINT pk_password_reset_tokens PRIMARY KEY (id),
    CONSTRAINT uq_password_reset_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_password_reset_tokens_single_owner
        CHECK ((admin_user_id IS NOT NULL)::int + (client_user_id IS NOT NULL)::int = 1),
    CONSTRAINT ck_password_reset_tokens_hash_format
        CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_password_reset_tokens_expiry
        CHECK (expires_at > created_at),
    CONSTRAINT ck_password_reset_tokens_used_after_created
        CHECK (used_at IS NULL OR used_at >= created_at)
);

-- 3. copy back only tokens that still point at a real account ---------
INSERT INTO password_reset_tokens
       (admin_user_id, client_user_id, token_hash, created_at, expires_at, used_at)
SELECT t.admin_user_id, t.client_user_id, t.token_hash, t.created_at, t.expires_at, t.used_at
  FROM tmp_password_reset_tokens t
 WHERE (t.admin_user_id  IS NOT NULL AND EXISTS (SELECT 1 FROM admin_users  a WHERE a.id = t.admin_user_id))
    OR (t.client_user_id IS NOT NULL AND EXISTS (SELECT 1 FROM client_users c WHERE c.id = t.client_user_id));

-- 4. only the newest unused token per account may stay live -----------
UPDATE password_reset_tokens p
   SET used_at = p.created_at
 WHERE p.used_at IS NULL
   AND EXISTS (SELECT 1
                 FROM password_reset_tokens n
                WHERE n.used_at IS NULL
                  AND n.id > p.id
                  AND (n.admin_user_id  = p.admin_user_id
                    OR n.client_user_id = p.client_user_id));

CREATE UNIQUE INDEX uq_password_reset_tokens_active_admin
    ON password_reset_tokens (admin_user_id)
    WHERE used_at IS NULL AND admin_user_id IS NOT NULL;

CREATE UNIQUE INDEX uq_password_reset_tokens_active_client
    ON password_reset_tokens (client_user_id)
    WHERE used_at IS NULL AND client_user_id IS NOT NULL;

CREATE INDEX ix_password_reset_tokens_admin  ON password_reset_tokens (admin_user_id)  WHERE admin_user_id  IS NOT NULL;
CREATE INDEX ix_password_reset_tokens_client ON password_reset_tokens (client_user_id) WHERE client_user_id IS NOT NULL;
CREATE INDEX ix_password_reset_tokens_expires ON password_reset_tokens (expires_at);

-- 5. a token, once used, can never be un-used or re-pointed ----------
CREATE FUNCTION fn_password_reset_token_protect() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.token_hash     IS DISTINCT FROM OLD.token_hash
    OR NEW.admin_user_id  IS DISTINCT FROM OLD.admin_user_id
    OR NEW.client_user_id IS DISTINCT FROM OLD.client_user_id
    OR NEW.expires_at     IS DISTINCT FROM OLD.expires_at
    OR NEW.created_at     IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'A password reset token can only be marked as used.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    IF OLD.used_at IS NOT NULL AND NEW.used_at IS DISTINCT FROM OLD.used_at THEN
        RAISE EXCEPTION 'A used password reset token cannot be changed.'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;

    RETURN NEW;
END
$$;

CREATE TRIGGER trg_password_reset_token_protect
    BEFORE UPDATE ON password_reset_tokens
    FOR EACH ROW EXECUTE FUNCTION fn_password_reset_token_protect();
